// Generates docs/THIRD_PARTY_LICENSES.md from `cargo metadata` and `npm query`, and fails if
// any dependency uses a license outside the allowlist in docs/DECISIONS.md (D-004).
// Usage: npm run licenses            (regenerate)
//        node scripts/license-report.mjs --check   (fail if the committed report is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { hasCommand, ROOT, run } from './lib/repo.mjs';

const ALLOWED = new Set([
  'MIT', 'MIT-0', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib',
  'Unicode-3.0', 'Unicode-DFS-2016', 'MPL-2.0', '0BSD', 'CC0-1.0', 'BlueOak-1.0.0',
  'Apache-2.0 WITH LLVM-exception',
  // D-058: argparse (markdown-it's CLI only; not in the app bundle).
  'PSF-2.0',
]);
const OUT = join(ROOT, 'docs', 'THIRD_PARTY_LICENSES.md');

/** D-064: OFL-1.1 is allowed for bundled font packages only. */
const fontLicense = (p) => p.license === 'OFL-1.1' && p.name.startsWith('@fontsource');

/** Evaluate a simple SPDX expression: `A OR B` needs one allowed, `A AND B` needs both. */
function allowed(expr) {
  if (!expr) return false;
  const clean = expr.replace(/[()]/g, ' ').replace(/\//g, ' OR ').trim();
  return clean
    .split(/\s+OR\s+/)
    .some((alt) => alt.split(/\s+AND\s+/).every((id) => ALLOWED.has(id.trim())));
}

function rustCrates() {
  if (!hasCommand('cargo')) return null;
  const meta = JSON.parse(
    run('cargo', ['metadata', '--format-version', '1', '--locked'], { capture: true }).stdout,
  );
  const members = new Set(meta.workspace_members);
  return meta.packages
    .filter((p) => !members.has(p.id))
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? '' }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function npmPackages() {
  const all = JSON.parse(run('npm', ['query', '*'], { capture: true }).stdout);
  const seen = new Map();
  for (const p of all) {
    if (!p.location || p.location === 'web') continue; // our own workspace packages
    const license = typeof p.license === 'string' ? p.license : (p.license?.type ?? '');
    const key = `${p.name}@${p.version}`;
    if (!seen.has(key)) seen.set(key, { name: p.name, version: p.version, license, dev: !!p.dev });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const crates = rustCrates();
const npm = npmPackages();
const bad = [
  ...(crates ?? []).filter((c) => !allowed(c.license)).map((c) => `crate ${c.name} ${c.version}: ${c.license || '(none)'}`),
  ...npm.filter((p) => !allowed(p.license) && !fontLicense(p)).map((p) => `npm ${p.name} ${p.version}: ${p.license || '(none)'}`),
];

const lines = [
  '# Third-party licenses',
  '',
  '_Generated by `npm run licenses` (scripts/license-report.mjs). Do not edit by hand._',
  '',
  `Allowed licenses (D-004): ${[...ALLOWED].join(', ')}.`,
  '',
  '## Rust crates',
  '',
];
if (crates === null) {
  lines.push('_Rust is not installed on the machine that generated this report._');
} else {
  lines.push('| Crate | Version | License |', '|---|---|---|');
  for (const c of crates) lines.push(`| ${c.name} | ${c.version} | ${c.license} |`);
}
lines.push('', '## npm packages', '', '| Package | Version | License | Dev only |', '|---|---|---|---|');
for (const p of npm) lines.push(`| ${p.name} | ${p.version} | ${p.license} | ${p.dev ? 'yes' : 'no'} |`);
const report = `${lines.join('\n')}\n`;

if (bad.length) {
  console.error(`license-report: disallowed or missing licenses:\n  ${bad.join('\n  ')}`);
  process.exit(1);
}

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  } catch {}
  if (crates !== null && current !== report) {
    console.error('license-report: docs/THIRD_PARTY_LICENSES.md is stale. Run `npm run licenses`.');
    process.exit(1);
  }
  console.log('license-report: all dependency licenses allowed; report is current.');
} else {
  writeFileSync(OUT, report);
  console.log(`license-report: wrote docs/THIRD_PARTY_LICENSES.md (${crates?.length ?? 0} crates, ${npm.length} npm packages).`);
}
