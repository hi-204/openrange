// Offline support (D-080): after a production build, write dist/sw.js, a service worker that
// pre-caches every file of the build, so the whole app (lessons, charts, the solver's WASM,
// equity data) works without a network after the first visit. No dependency: the worker is
// a few lines, generated with the exact file list and a version hash.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

function walk(dir: string, out: string[] = []): string[] {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** The service worker source for a list of URLs (relative to the worker) and a version. */
export function serviceWorker(files: string[], version: string): string {
  return `// Generated by web/offline.ts at build time. Do not edit.
const CACHE = 'openrange-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('openrange-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Same-origin GETs: answer from the cache, fall back to the network. Page loads (the app uses
// hash routes, so there is only one page) fall back to the cached index.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    // ignoreVary: the server may send "Vary: Accept-Encoding", and the browser's request
    // headers differ between the pre-cache fetch and a page load; the files are static.
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).catch(() =>
        req.mode === 'navigate' ? caches.match('./', { ignoreVary: true }).then((r) => r || Response.error()) : Response.error(),
      );
    }),
  );
});
`;
}

export function offline(): Plugin {
  let outDir = 'dist';
  return {
    name: 'openrange-offline',
    apply: 'build',
    configResolved(c) {
      outDir = c.build.outDir;
    },
    closeBundle() {
      const files = walk(outDir)
        .map((f) => relative(outDir, f).split(sep).join('/'))
        .filter((f) => f !== 'sw.js')
        .sort();
      const h = createHash('sha256');
      for (const f of files) h.update(f).update(readFileSync(join(outDir, f)));
      writeFileSync(join(outDir, 'sw.js'), serviceWorker(files, h.digest('hex').slice(0, 12)));
      console.log(`offline: dist/sw.js pre-caches ${files.length} files`);
    },
  };
}
